#!/usr/bin/env node
// Writes dist/sw.js after `vite build`: a small offline-first service worker
// that precaches every built file (hashed asset names make the list a version)
// and keeps the Google Font files fresh with stale-while-revalidate.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dist = path.join(root, "dist");

function walk(dir, base = "") {
  const out = [];
  for (const name of readdirSync(dir)) {
    const rel = base ? `${base}/${name}` : name;
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full, rel));
    else if (name !== "sw.js") out.push(rel);
  }
  return out;
}

const files = walk(dist).sort();
const version = createHash("sha1").update(files.join("\n")).digest("hex").slice(0, 10);
const precache = ["./", ...files.map((f) => "./" + f)];

const sw = `// generated by scripts/sw.mjs — do not edit
const CACHE = "sfd-${version}";
const PRECACHE = ${JSON.stringify(precache)};
const FONT_CACHE = "sfd-fonts";

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE && k !== FONT_CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  // fonts: serve cached, refresh in the background
  if (url.host === "fonts.googleapis.com" || url.host === "fonts.gstatic.com") {
    e.respondWith(
      caches.open(FONT_CACHE).then((c) =>
        c.match(req).then((hit) => {
          const net = fetch(req).then((res) => {
            if (res.ok || res.type === "opaque") c.put(req, res.clone());
            return res;
          }).catch(() => hit);
          return hit || net;
        }),
      ),
    );
    return;
  }
  if (url.origin !== self.location.origin) return;
  // page loads: network first (picks up new versions), cached shell when offline
  if (req.mode === "navigate") {
    e.respondWith(fetch(req).catch(() => caches.match("./", { cacheName: CACHE, ignoreVary: true }).then((r) => r || caches.match(req, { ignoreVary: true }))));
    return;
  }
  // built files are content-hashed: cache first (ignoreVary: module scripts are
  // CORS requests and servers often add "Vary: Origin")
  e.respondWith(caches.match(req, { ignoreVary: true }).then((hit) => hit || fetch(req)));
});
`;
writeFileSync(path.join(dist, "sw.js"), sw);
console.log(`wrote dist/sw.js (${files.length} files, cache sfd-${version})`);
